/**
 * 게임 전역 상수.
 *
 * 호스트와 클라이언트가 같은 값을 써야 하므로 shared 에 둔다.
 * 클라이언트 예측(prediction)이 호스트 시뮬레이션과 어긋나지 않으려면
 * 이동 관련 상수는 반드시 여기 한 곳에서만 정의되어야 한다.
 */

/** 호스트 시뮬레이션 틱 레이트. 스냅샷도 매 틱 브로드캐스트한다. */
export const TICK_HZ = 20
export const TICK_MS = 1000 / TICK_HZ
export const TICK_DT = 1 / TICK_HZ

/**
 * 클라이언트 예측도 호스트와 같은 TICK_HZ 고정 스텝으로 돈다.
 *
 * 프레임 단위(60fps)로 적분하면 직선 구간에서는 결과가 같지만, 벽을 스치며
 * 미끄러질 때 스텝 크기에 따라 이동 거리가 달라져 예측이 계속 어긋난다.
 * 입력 전송도 이 스텝에 맞춰서 보낸다. 호스트가 틱당 최신 입력 하나만 쓰므로
 * 더 자주 보내봐야 대역폭만 쓴다.
 */

/**
 * 미로 한 칸의 월드 크기(단위)와 벽 두께.
 *
 * WALL_T 를 CELL 의 절반으로 잡으면 "통로 폭 = 벽 두께" 가 되어, 얇은 칸막이가 아니라
 * 블록을 쌓아 만든 구조물처럼 보인다. 통로 3 · 벽 3 의 균일한 블록 격자가 된다.
 *
 * CELL 을 키우면 미로를 가로지르는 거리도 함께 늘어나므로 이동 속도도 같이 올렸다.
 * 상한 확인: 41칸 * 8 = 328 단위. 스냅샷 좌표 i16 의 1cm 정밀도로는 327.67 이 한계라
 * 아슬아슬하게 넘친다. 그래서 protocol.ts 의 COORD_SCALE 을 50(2cm)으로 낮췄다.
 * 2cm 오차는 플레이어 반경 0.55 에 비하면 눈에 띄지 않는다.
 */
export const CELL = 8
/** 벽 두께. CELL 의 절반이라 통로 폭과 정확히 같다 — 균일한 블록 격자가 된다. */
export const WALL_T = 4
/** 벽 높이. 두꺼워진 만큼 높이도 올려야 블록처럼 보인다. */
export const WALL_H = 5

/** 플레이어 충돌 반지름. */
export const PLAYER_R = 0.55
/** 플레이어 이동 속도 (단위/초). CELL 이 4 → 6 으로 커진 만큼 함께 올렸다. */
export const PLAYER_SPEED = 9.5
/** 눈높이 (1인칭 카메라). */
export const EYE_H = 1.55

/** 열쇠 / 탈출구 상호작용 반경. */
export const PICKUP_R = 1.8
export const EXIT_R = 2.2
/** 상점 / 던전 입구에 반응하는 반경. */
export const INTERACT_R = 3.2

/**
 * 가림 판정에 쓰는 여유. 선분이 벽을 살짝 스칠 때 깜빡이지 않게 해준다.
 *
 * 반드시 PLAYER_R 보다 작아야 한다. 크면 플레이어가 붙어 선 벽까지 선분에 걸려서,
 * 캐릭터 "앞"에 있는 벽마저 투명해진다. resolveCircle 이 플레이어를 벽면에서 정확히
 * PLAYER_R 만큼 떼어놓기 때문이다. (0.6 으로 뒀을 때 표본의 54.5% 에서 앞벽이 뚫렸다.)
 */
export const OCCLUSION_PAD = PLAYER_R * 0.6

/** 원격 플레이어 렌더링 지연. 스냅샷 2개분 버퍼를 확보해 튐을 막는다. */
export const INTERP_DELAY_MS = 100

/** 로컬 예측 위치가 권위 위치와 이 이상 벌어지면 부드럽게 보정하지 않고 즉시 스냅한다. */
export const RECONCILE_SNAP_DIST = 2.5

/**
 * 예측 오차가 1/e 로 줄어드는 데 걸리는 시간(초).
 *
 * "프레임당 몇 %" 로 잡으면 60fps 기기와 20fps 기기에서 보정 속도가 3배 차이 난다.
 * 느린 기기일수록 오차가 오래 남아 캐릭터가 밀리는 느낌이 되므로,
 * 반드시 프레임이 아니라 시간을 기준으로 감쇠시켜야 한다.
 */
export const RECONCILE_TAU = 0.12

export const MAX_PLAYERS = 4

/** 레벨 클리어 후 다음 레벨로 넘어가기까지의 대기(초). */
export const CLEAR_HOLD_SEC = 3

